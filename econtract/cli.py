def register_cli(app: Flask) -> None:
    @app.cli.command("init-db")
    @with_appcontext
    def init_db_cmd():
        """データベースを初期化する."""
        db.create_all()
        click.echo("✅ データベースを初期化しました。")

    @app.cli.command("seed")
    @with_appcontext
    def seed_cmd():
        """サンプルテンプレートと管理者を投入する."""
        # 管理者ユーザー
        admin = User.query.filter_by(email="admin@example.com").first()
        if not admin:
            admin = User(
                email="admin@example.com",
                name="管理者",
                department="管理部",
                is_admin=True,
            )
            admin.set_password("admin1234")
            db.session.add(admin)
            click.echo("👤 管理者: admin@example.com / admin1234")

        demo = User.query.filter_by(email="legal@example.com").first()
        if not demo:
            demo = User(email="legal@example.com", name="法務 太郎", department="法務部")
            demo.set_password("legal1234")
            db.session.add(demo)
            click.echo("👤 利用者: legal@example.com / legal1234")

        existing = {t.name for t in Template.query.all()}
        for t in SAMPLE_TEMPLATES:
            if t["name"] in existing:
                continue
            db.session.add(Template(
                name=t["name"],
                category=t["category"],
                description=t["description"],
                body=t["body"],
                variables_json=json.dumps(t["variables"], ensure_ascii=False),
            ))
        db.session.commit()
        click.echo("✅ サンプルテンプレートを投入しました。")
